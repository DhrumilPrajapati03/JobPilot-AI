"""Resume data models.

Represents the structured resume content that flows through
the 3-layer resume architecture (Content JSON → Template → PDF).
"""

from datetime import datetime

from pydantic import BaseModel, Field


class ResumeExperience(BaseModel):
    """A single work experience entry."""
    company: str
    role: str
    duration: str
    bullets: list[str] = Field(default_factory=list)


class ResumeSkills(BaseModel):
    """Categorised skills list."""
    primary: list[str] = Field(default_factory=list)
    secondary: list[str] = Field(default_factory=list)


class ResumeProject(BaseModel):
    """A portfolio/personal project entry."""
    name: str
    description: str = ""
    tech: list[str] = Field(default_factory=list)


class ResumeEducation(BaseModel):
    """An education entry."""
    institution: str
    degree: str
    year: str = ""


class ResumeCertification(BaseModel):
    """A certification entry."""
    name: str
    issuer: str = ""
    year: str = ""


class Resume(BaseModel):
    """Full resume content model (Layer 2 of the 3-layer architecture).

    This JSON structure is what the LLM edits. It never touches
    HTML or CSS directly. The Jinja2 template renders this into
    a pixel-perfect PDF via WeasyPrint.

    Attributes:
        id: Unique resume identifier.
        user_id: Owner user ID.
        name: Full name on resume.
        headline: Professional headline.
        summary: Tailored 3-line professional summary.
        experience: List of work experiences.
        skills: Categorised skills.
        projects: Portfolio projects.
        education: Education entries.
        certifications: Professional certifications.
        version: Resume version string.
        created_at: Creation timestamp.
        updated_at: Last update timestamp.
    """
    id: str | None = None
    user_id: str | None = None
    name: str = ""
    headline: str = ""
    summary: str = ""
    experience: list[ResumeExperience] = Field(default_factory=list)
    skills: ResumeSkills = Field(default_factory=ResumeSkills)
    projects: list[ResumeProject] = Field(default_factory=list)
    education: list[ResumeEducation] = Field(default_factory=list)
    certifications: list[ResumeCertification] = Field(default_factory=list)
    version: str = "base"
    created_at: datetime | None = None
    updated_at: datetime | None = None


class TailoredResume(BaseModel):
    """A JD-tailored version of the user's resume.

    Generated by the Resume Tailor Agent for a specific
    job application.

    Attributes:
        id: Unique tailored resume ID.
        application_id: Associated job application.
        version: Version number for this tailored variant.
        content: The tailored resume content JSON.
        pdf_url: URL to the generated PDF in Supabase Storage.
        keyword_match_score: ATS keyword match score (0-100).
        missing_keywords: Keywords from JD not found in resume.
        generated_at: Generation timestamp.
    """
    id: str | None = None
    application_id: str = ""
    version: int = 1
    content: Resume | None = None
    pdf_url: str = ""
    keyword_match_score: float = 0.0
    missing_keywords: list[str] = Field(default_factory=list)
    generated_at: datetime | None = None
